"use client";

import React, { useState } from "react";
import { ResearchRun } from "@/lib/types";
import { FileSpreadsheet, FileCode, Copy, Check } from "lucide-react";

interface ExportActionsProps {
  run: ResearchRun;
}

export function ExportActions({ run }: ExportActionsProps) {
  const [copied, setCopied] = useState(false);

  const handleCopySummary = () => {
    const lines = [
      `STARALL BRIEFING: ${run.startup_profile.sector} (${run.startup_profile.sub_sector})`,
      `Target Stage: ${run.startup_profile.stage} | Target Geography: ${run.startup_profile.geography}`,
      `Lookback Window: ${run.lookback_start} to ${run.lookback_end}`,
      `Discovered Comparables: ${run.comparable_companies.length} verified companies`,
      "",
      "TOP RANKED INVESTORS:",
      ...run.investors.slice(0, 10).map(
        (inv) =>
          `#${inv.rank} ${inv.name} (Score: ${inv.total_score}/100, Confidence: ${inv.confidence_score}%)` +
          `\n   Backed: ${inv.backed_comparables.map((b) => b.company_name).join(", ")}` +
          `\n   Cheque: ${inv.cheque_size.formatted}` +
          `\n   Route: ${inv.approach_route.label} (${inv.approach_route.url || "via portfolio"})` +
          `\n   Lead Partner: ${inv.lead_partner.name || "Not publicly verified"}`
      ),
      "",
      `Generated by StarAll. Request ID: ${run.request_id}`,
    ];

    navigator.clipboard.writeText(lines.join("\n"));
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="flex flex-wrap items-center gap-2">
      <button
        type="button"
        onClick={handleCopySummary}
        className="px-3 py-1.5 rounded-lg bg-[#ffffff] hover:bg-[#f6f3eb] border border-[#d6d0c4] text-xs font-medium text-stone-800 flex items-center space-x-1.5 transition-colors shadow-xs"
      >
        {copied ? (
          <>
            <Check className="w-3.5 h-3.5 text-amber-800" />
            <span className="text-amber-900">Summary copied</span>
          </>
        ) : (
          <>
            <Copy className="w-3.5 h-3.5 text-stone-500" />
            <span>Copy summary</span>
          </>
        )}
      </button>

      <a
        href={`/api/export/${run.request_id}?format=csv`}
        download
        className="px-3 py-1.5 rounded-lg bg-[#ffffff] hover:bg-[#f6f3eb] border border-[#d6d0c4] text-xs font-medium text-stone-800 flex items-center space-x-1.5 transition-colors shadow-xs"
      >
        <FileSpreadsheet className="w-3.5 h-3.5 text-stone-500" />
        <span>Export CSV</span>
      </a>

      <a
        href={`/api/export/${run.request_id}?format=json`}
        download
        className="px-3 py-1.5 rounded-lg bg-[#ffffff] hover:bg-[#f6f3eb] border border-[#d6d0c4] text-xs font-medium text-stone-800 flex items-center space-x-1.5 transition-colors shadow-xs"
      >
        <FileCode className="w-3.5 h-3.5 text-stone-500" />
        <span>Export JSON</span>
      </a>
    </div>
  );
}
